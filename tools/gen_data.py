"""Writes src/grus_data.c from data/export.json: parameter tables, factory patterns and factory samples (as flash bytes)."""
import json,sys
d=json.load(open('data/export.json'))
f=lambda x:repr(float(x)) if x is not None else '0.0'
ff=lambda x:repr(float(x))+'f'
o=['/* SPDX-License-Identifier: GPL-3.0-only\n   Generated by tools/gen_data.py from the browser prototype. Do not edit by hand. */','#include "grus.h"','']
o.append('const uint8_t grus_pn[GRUS_ENG_N][8]={'+','.join('{'+','.join(str(p['n']) for p in e['params'])+'}' for e in d['eng'])+'};')
o.append('const float grus_base[GRUS_ENG_N][8]={'+','.join('{'+','.join(ff(x) for x in e['base'])+'}' for e in d['eng'])+'};')
o.append('const char*const grus_eng_name[GRUS_ENG_N]={'+','.join('"%s"'%e['name'] for e in d['eng'])+'};')
o.append('const uint8_t grus_mod_n[8]={'+','.join(str(p['n']) for p in d['mod'])+'};')
o.append('const gf grus_ratios[9]={'+','.join(f(x) for x in d['ratios'])+'};')
o.append('const int8_t grus_chi[8][5]={'+','.join('{%d,'%len(c)+','.join(map(str,c))+'}' for c in d['chn'])+'};')
o.append('const int8_t grus_stc[8][6]={'+','.join('{%d,'%len(c)+','.join(map(str,c))+'}' for c in d['stc'])+'};')
o.append('const gf grus_lrate[8]={'+','.join(f(x) for x in d['lrate'])+'};')
o.append('const gf grus_divs[5]={'+','.join(f(x) for x in d['divs'])+'};')
o.append('const uint8_t grus_mods[10][2]={'+','.join('{%d,%d}'%tuple(m) for m in d['mods'])+'};')
o.append('')
import math
def jsr(x):return int(math.floor(x+0.5))   # JavaScript's Math.round (Python's round() rounds halves to even)
def q16(v):return max(0,min(65535,jsr(v*65535)))
def step(s):
    a=['.vel=%d'%q16(s['vel'])]
    if s['note']:a.append('.note=%d'%s['note'])
    if s['prob']!=100:a.append('.skip=%d'%(100-jsr(s['prob'])))
    if s['rat']!=1:a.append('.rat=%d'%s['rat'])
    if s['slope']:a.append('.slope=%d'%jsr(s['slope']*100))
    if s['nudge']:a.append('.nudge=%d'%jsr(s['nudge']*100))
    if s['mod']:a.append('.mod=%d'%s['mod'])
    L=s['locks'][:6]
    if L:a.append('.nlock=%d,.lid={%s},.lv={%s}'%(len(L),','.join(str(i) for i,v in L),','.join(str(q16(v)) for i,v in L)))
    if s['ci']:a.append('.nci=%d,.ci={%s}'%(len(s['ci']),','.join(map(str,s['ci']))))
    return '{%d,{%s}}'%(s['i'],','.join(a))
for k,p in enumerate(d['pats']):
    for ti,t in enumerate(p['tracks']):
        if t['steps']:o.append('static const grus_step_at p%dt%d[%d]={%s};'%(k,ti,len(t['steps']),','.join(step(x) for x in t['steps'])))
o.append('const grus_pattern_init grus_factory[GRUS_FACTORY_N]={')
for k,p in enumerate(d['pats']):
    s=p['sl'];o.append(' {.name="%s",.bpm=%s,.swing=%s,.vol=%s,.rsize=%s,.rdamp=%s,.dtype=%d,.dtime=%s,.dfb=%s,.dtone=%s,.dmod=%s,.dret=%s,.voices=%d,.tr={'%(
        p['name'],f(s['bpm']),f(s['swing']),f(s['vol']),f(s['rsize']),f(s['rdamp']),int(s['dtype']),f(s['dtime']),f(s['dfb']),f(s['dtone']),f(s['dmod']),f(s['dret']),int(s['voices'])))
    for ti,t in enumerate(p['tracks']):
        o.append('  {.eng=%d,.len=%d,.div=%d,.dir=%d,.mute=%d,.nst=%d,.st=%s,.pv={%s},.mx={%s},.mo={%s}},'%(t['eng'],t['len'],t['div'],t['dir'],t['mute'],len(t['steps']),
            'p%dt%d'%(k,ti) if t['steps'] else '0',','.join(f(x) for x in t['pv']),','.join(f(x) for x in t['mx']),','.join(f(x) for x in t['mo'])))
    o.append(' }},')
o.append('};')
o.append('const grus_preset grus_presets[GRUS_ENG_N][GRUS_PRESETS]={'+','.join('{'+','.join('{"%s",%d,{%s}}'%(p['name'],sum(1<<i for i,x in enumerate(p['v']) if x is not None),','.join(f(x if x is not None else 0) for x in p['v'])) for p in E)+'}' for E in d['pres'])+'};')
o.append('')
for k,m in enumerate(d['smp']):
    a=m['a'];o.append('static const uint8_t smp%d[%d]={'%(k,len(a)))
    for i in range(0,len(a),40):o.append(','.join(map(str,a[i:i+40]))+',')
    o.append('};')
o.append('const grus_sample grus_factory_smp[GRUS_SMP_SLOTS]={'+','.join('{"%s",%d,smp%d,%d,{%s}}'%(m['name'],m['n'],k,len(m['sl']),','.join(map(str,m['sl']))) for k,m in enumerate(d['smp']))+'};')
open('src/grus_data.c','w').write('\n'.join(o)+'\n')
print('wrote src/grus_data.c',sum(len(x) for x in o)//1024,'KB of source')
